-- Casos especiales de un día: persona que recogerá al alumno en una fecha concreta.
-- Lo usa el portal de papás (módulo restringido hasta liberación).

CREATE TABLE IF NOT EXISTS public.alumno_caso_especial (
  caso_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alumno_ref integer NOT NULL,
  alumno_id integer NOT NULL REFERENCES public.alumno (alumno_id) ON DELETE CASCADE,
  fecha date NOT NULL,
  persona_nombre text NOT NULL,
  parentesco text NOT NULL DEFAULT '',
  telefono text NOT NULL DEFAULT '',
  motivo text NOT NULL DEFAULT '',
  contacto_id integer NULL,
  creado_por text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.alumno_caso_especial IS
  'Autorización de un día: quién puede recoger al alumno en una fecha específica.';

CREATE INDEX IF NOT EXISTS alumno_caso_especial_alumno_ref_fecha_idx
  ON public.alumno_caso_especial (alumno_ref, fecha DESC);

CREATE INDEX IF NOT EXISTS alumno_caso_especial_alumno_id_fecha_idx
  ON public.alumno_caso_especial (alumno_id, fecha DESC);

DROP TRIGGER IF EXISTS alumno_caso_especial_updated_at ON public.alumno_caso_especial;
CREATE TRIGGER alumno_caso_especial_updated_at
  BEFORE UPDATE ON public.alumno_caso_especial
  FOR EACH ROW
  EXECUTE FUNCTION system.update_updated_at();

ALTER TABLE public.alumno_caso_especial ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alumno_caso_especial FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS servicios_insforge_deny_anon ON public.alumno_caso_especial;
CREATE POLICY servicios_insforge_deny_anon ON public.alumno_caso_especial
  FOR ALL TO anon, authenticated USING (false) WITH CHECK (false);
REVOKE ALL ON public.alumno_caso_especial FROM anon, authenticated;
