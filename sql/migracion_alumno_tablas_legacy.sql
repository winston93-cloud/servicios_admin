-- Trigger reutilizable: equivalente a ON UPDATE CURRENT_TIMESTAMP (MySQL)
CREATE OR REPLACE FUNCTION public.set_updated_at_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.alumno_actualizacion := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

