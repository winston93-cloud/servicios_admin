CREATE TABLE public.alumno (
  alumno_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alumno_ref INTEGER NULL,
  alumno_app VARCHAR(50) NULL,
  alumno_apm VARCHAR(50) NULL,
  alumno_nombre VARCHAR(50) NULL,
  alumno_nivel SMALLINT NULL,
  alumno_grado SMALLINT NULL,
  alumno_grupo SMALLINT NULL,
  alumno_status SMALLINT NOT NULL,
  alumno_nuevo_ingreso SMALLINT NOT NULL,
  alumno_ciclo_escolar SMALLINT NULL,
  alumno_registro DATE NULL,
  alumno_alta DATE NULL,
  alumno_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  alumno_boleta SMALLINT NOT NULL,
  mes SMALLINT NOT NULL,
  secret_key VARCHAR(64) NOT NULL,
  motivo VARCHAR(200) NOT NULL,
  responsable VARCHAR(50) NOT NULL,
  estatus_key SMALLINT NOT NULL DEFAULT 0,
  digito INTEGER NOT NULL,
  hijo SMALLINT NOT NULL DEFAULT 0
);

COMMENT ON COLUMN public.alumno.alumno_nivel IS '1= Maternal; 2= Kinder; 3= Primaria; 4= Secundaria';
COMMENT ON COLUMN public.alumno.alumno_status IS '0= Baja General; 1= Activo; 2= Inactivo; 3= Baja Temporal Administrativa; 5= Bloqueo por Psicología';
COMMENT ON COLUMN public.alumno.alumno_nuevo_ingreso IS '0= Reinscrito; 1= Nuevo Ingreso de Agenda';
COMMENT ON COLUMN public.alumno.alumno_ciclo_escolar IS '12= 2015-2016; 13= 2016-2017; 14= 2017-2018; …';
COMMENT ON COLUMN public.alumno.alumno_registro IS 'Registro de la Solicitud de Inscripción; NULL si no ha realizado la solicitud';
COMMENT ON COLUMN public.alumno.alumno_alta IS 'Alta del pase de agenda';

CREATE UNIQUE INDEX alumno_ref ON public.alumno (alumno_ref);

CREATE TRIGGER trg_alumno_actualizacion
  BEFORE UPDATE ON public.alumno
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at_timestamp();

