#!/usr/bin/env node
/**
 * Genera el esquema de Uniformes (InsForge q488j9fg) para crearlo en Winston Servicios,
 * leyendo el catálogo de Postgres de Uniformes (solo lectura).
 *
 *   node scripts/generar-esquema-uniformes-winston.mjs
 *
 * Escribe dos migraciones:
 *   - …_uniformes_tablas.sql: tablas, llaves, CHECK, UNIQUE, RLS y políticas (antes de copiar datos).
 *   - …_uniformes_logica.sql: FK, índices, funciones y triggers (después de copiar, para que los
 *     triggers de auditoría, folios y pedidos no se disparen con la copia).
 *
 * No incluye alumno, ciclos_escolares ni usuario: Uniformes usa las de Winston.
 * No reemplaza funciones que ya existen en Winston (update_updated_at_column) ni las de ciclos.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const UNIFORMES_DIR = '/home/mario/Proyectos/uniformes'
const EXCLUIR_TABLAS = ['alumno', 'ciclos_escolares', 'usuario']
const EXCLUIR_FUNCIONES = ['update_updated_at_column', 'asegurar_un_ciclo_actual', 'update_ciclo_escolar_updated_at']
const SECUENCIAS = ['cotizacion_folio_seq', 'devoluciones_folio_seq']

function q(sql) {
  const out = execFileSync('npx', ['-y', '@insforge/cli@latest', 'db', 'query', sql, '--json'], {
    cwd: UNIFORMES_DIR,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
  return JSON.parse(out).rows
}

const lista = (xs) => xs.map((x) => `'${x}'`).join(',')
const tablas = q(
  `select c.relname from pg_class c where c.relnamespace='public'::regnamespace and c.relkind='r'
   and c.relname not in (${lista(EXCLUIR_TABLAS)}) order by 1`,
).map((r) => r.relname)

const columnas = q(
  `select c.relname tabla, a.attname col, format_type(a.atttypid, a.atttypmod) tipo, a.attnotnull nn,
          pg_get_expr(d.adbin, d.adrelid) def, a.attidentity ident
   from pg_attribute a join pg_class c on c.oid=a.attrelid
   left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
   where c.relnamespace='public'::regnamespace and c.relkind='r' and a.attnum>0 and not a.attisdropped
     and c.relname in (${lista(tablas)})
   order by c.relname, a.attnum`,
)

const restricciones = q(
  `select c.relname tabla, k.conname nombre, k.contype tipo, pg_get_constraintdef(k.oid) def
   from pg_constraint k join pg_class c on c.oid=k.conrelid
   where c.relnamespace='public'::regnamespace and c.relname in (${lista(tablas)})
   order by c.relname, k.contype, k.conname`,
)

const indices = q(
  `select t.relname tabla, pg_get_indexdef(i.indexrelid) def
   from pg_index i join pg_class t on t.oid=i.indrelid
   where t.relnamespace='public'::regnamespace and t.relname in (${lista(tablas)})
     and not exists (select 1 from pg_constraint k where k.conindid=i.indexrelid)
   order by 1, 2`,
)

const triggers = q(
  `select c.relname tabla, pg_get_triggerdef(t.oid) def
   from pg_trigger t join pg_class c on c.oid=t.tgrelid
   where not t.tgisinternal and c.relnamespace='public'::regnamespace and c.relname in (${lista(tablas)})
   order by 1, 2`,
)

const politicas = q(
  `select tablename tabla, policyname nombre, permissive, roles::text roles, cmd, qual, with_check
   from pg_policies where schemaname='public' and tablename in (${lista(tablas)}) order by 1, 2`,
)

const rls = q(
  `select relname tabla from pg_class where relnamespace='public'::regnamespace and relrowsecurity
   and relname in (${lista(tablas)})`,
).map((r) => r.tabla)

const funciones = q(
  `select p.proname nombre, pg_get_functiondef(p.oid) def
   from pg_proc p
   where p.pronamespace='public'::regnamespace and p.prokind in ('f','p')
     and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')
     and p.proname not in (${lista(EXCLUIR_FUNCIONES)})
   order by 1`,
)

const secuencias = q(
  `select sequencename nombre, data_type tipo, start_value inicio, increment_by inc, min_value mn, max_value mx
   from pg_sequences where schemaname='public' and sequencename in (${lista(SECUENCIAS)})`,
)

const ident = (s) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '""')}"`)

let tablasSql = `-- Uniformes (InsForge q488j9fg) → Winston Servicios: tablas, llaves, RLS y políticas.
-- Generado por scripts/generar-esquema-uniformes-winston.mjs. Solo crea objetos nuevos; no toca tablas de Winston.

`
for (const s of secuencias) {
  tablasSql += `CREATE SEQUENCE IF NOT EXISTS public.${s.nombre} AS ${s.tipo} START WITH ${s.inicio} INCREMENT BY ${s.inc} MINVALUE ${s.mn} MAXVALUE ${s.mx};\n`
}
tablasSql += '\n'

for (const t of tablas) {
  const cols = columnas.filter((c) => c.tabla === t).map((c) => {
    let linea = `  ${ident(c.col)} ${c.tipo}`
    if (c.ident === 'a') linea += ' GENERATED ALWAYS AS IDENTITY'
    else if (c.ident === 'd') linea += ' GENERATED BY DEFAULT AS IDENTITY'
    else if (c.def != null) linea += ` DEFAULT ${c.def}`
    if (c.nn) linea += ' NOT NULL'
    return linea
  })
  const cons = restricciones
    .filter((r) => r.tabla === t && r.tipo !== 'f')
    .map((r) => `  CONSTRAINT ${ident(r.nombre)} ${r.def}`)
  tablasSql += `CREATE TABLE public.${ident(t)} (\n${[...cols, ...cons].join(',\n')}\n);\n`
  if (rls.includes(t)) tablasSql += `ALTER TABLE public.${ident(t)} ENABLE ROW LEVEL SECURITY;\n`
  for (const p of politicas.filter((x) => x.tabla === t)) {
    const roles = p.roles.replace(/[{}]/g, '').split(',').map(ident).join(', ')
    tablasSql += `CREATE POLICY ${ident(p.nombre)} ON public.${ident(t)} AS ${p.permissive} FOR ${p.cmd} TO ${roles}`
    if (p.qual != null) tablasSql += ` USING (${p.qual})`
    if (p.with_check != null) tablasSql += ` WITH CHECK (${p.with_check})`
    tablasSql += ';\n'
  }
  tablasSql += '\n'
}

let logicaSql = `-- Uniformes (InsForge q488j9fg) → Winston Servicios: FK, índices, funciones y triggers.
-- Aplicar DESPUÉS de copiar los datos. Las FK de Uniformes hacia usuario no se crean (usuario es de Winston).

`
for (const r of restricciones.filter((x) => x.tipo === 'f')) {
  if (/REFERENCES (public\.)?usuario\(/.test(r.def)) continue
  logicaSql += `ALTER TABLE public.${ident(r.tabla)} ADD CONSTRAINT ${ident(r.nombre)} ${r.def};\n`
}
logicaSql += '\n'
for (const i of indices) logicaSql += `${i.def};\n`
logicaSql += '\n'
for (const f of funciones) logicaSql += `${f.def.trim()};\n\n`
for (const t of triggers) logicaSql += `${t.def};\n`

const sello = '20261019190000'
writeFileSync(`migrations/${sello}_uniformes_tablas.sql`, tablasSql)
writeFileSync(`migrations/${Number(sello) + 100}_uniformes_logica.sql`, logicaSql)
console.log(
  `tablas=${tablas.length} columnas=${columnas.length} restricciones=${restricciones.length} indices=${indices.length} ` +
    `triggers=${triggers.length} politicas=${politicas.length} funciones=${funciones.length} secuencias=${secuencias.length}`,
)
